// Helper to generate realistic seat layout
export function generateSeatLayout(
  prefix: string,
  rows: number,
  cols: number,
  deck: "LOWER" | "UPPER",
  type: "SEATER" | "SLEEPER",
  basePrice: number,
  bookedSeatNumbers: string[] = [],
  ladiesSeatNumbers: string[] = []
): Seat[] {
  const seats: Seat[] = [];
  let seatIndex = 1;

  for (let r = 1; r <= rows; r++) {
    for (let c = 1; c <= cols; c++) {
      // Create aisle gap
      if (cols === 4 && c === 3) continue; // 2+2 layout with aisle
      if (cols === 3 && c === 2) continue; // 1+2 layout with aisle

      const seatNumber = `${prefix}${seatIndex < 10 ? "0" : ""}${seatIndex}`;
      let status: Seat["status"] = "AVAILABLE";

      if (bookedSeatNumbers.includes(seatNumber)) {
        status = "BOOKED";
      } else if (ladiesSeatNumbers.includes(seatNumber)) {
        status = "LADIES";
      }

      seats.push({
        id: `seat-${deck.toLowerCase()}-${seatNumber}`,
        seatNumber,
        deck,
        type,
        row: r,
        col: c,
        status,
        basePrice,
        currentPrice: basePrice,
      });

      seatIndex++;
    }
  }

  return seats;
}

